import UIKit
import XCTest

/// Shared launch, wait and navigation helpers for the Sable user-journey tests.
///
/// Rules every test follows:
/// - Launch with `Launch.*` arguments (`-uiTesting` wipes the library and defaults, so each test
///   starts clean; `-seedLibrary` imports the bundled fixtures; `-mockTranslation` installs the
///   offline mock translation provider).
/// - Find elements by the identifiers in `AX` (App/Core/AccessibilityIDs.swift, compiled into this
///   target too). No fixed sleeps: every wait is `waitForExistence` or a predicate expectation.
/// - Name screenshots "NN-what" so CI exports them as readable files.
class SableUITestCase: XCTestCase {
    var app: XCUIApplication!

    enum Launch {
        static let clean = ["-uiTesting"]
        static let seeded = ["-uiTesting", "-seedLibrary"]
        static let seededWithMockTranslation = ["-uiTesting", "-seedLibrary", "-mockTranslation"]
        /// Relaunch that keeps the library, defaults and timing written by a previous launch.
        static let relaunch: [String] = []
    }

    /// Facts about the bundled fixtures (Fixtures/UITestFixtures, generated by make_fixtures.sh).
    enum Fixture {
        static let mkvTitle = "Night Roof (MKV)"
        static let mp4Title = "Night Roof (MP4)"
        /// Matroska TrackNumbers: 1 video, 2–3 audio, 4 SRT en (default), 5 ASS en, 6 SRT fr.
        static let mkvEnglishSRT = "emb:mkv:4"
        static let mkvEnglishASS = "emb:mkv:5"
        static let mkvFrenchSRT = "emb:mkv:6"
        /// MP4 track IDs: 1 video, 2–3 audio, 4 mov_text en.
        static let mp4EnglishText = "emb:mp4:4"
        static let externalPrefix = "ext:"
        static let durationSeconds: TimeInterval = 40
        /// English dialogue (plain text, line breaks as spaces) — identical in every English track.
        static let englishLines = [
            "Mara, are you still awake?", "I can't sleep.", "The city is too loud tonight.",
            "Then let's go up to the roof.", "Is it safe?", "Trust me.", "Look — every light down there",
            "is someone's story.", "You sound like your father, Idris.", "He taught me to watch the night.",
            "Then let's watch it together, Mara.",
        ]
        static let frenchFragments = ["Mara", "dormir", "ville", "toit", "sûr", "confiance", "lumière", "père", "nuit", "ensemble"]
        /// night-roof.late.en.srt: every cue 2.5 s late. Cue "2" ("I can't sleep. …") starts at
        /// 10.000 s there while the matching speech burst in the audio starts at 7.500 s.
        static let lateCueID = "2"
        static let lateCueOriginalStart: TimeInterval = 10.0
        static let lateCueSpeechStart: TimeInterval = 7.5
    }

    enum Timeout {
        static let launch: TimeInterval = 30
        static let screen: TimeInterval = 15
        static let control: TimeInterval = 8
        static let playback: TimeInterval = 20
        static let translation: TimeInterval = 90
    }

    override func setUpWithError() throws {
        try super.setUpWithError()
        continueAfterFailure = false
        XCUIDevice.shared.orientation = .portrait
    }

    override func tearDownWithError() throws {
        // `hasSucceeded` is still false while the test is running, so count failures instead.
        if let app, app.state == .runningForeground, (testRun?.totalFailureCount ?? 0) > 0 {
            let testName = name.replacingOccurrences(of: "-[", with: "").replacingOccurrences(of: "]", with: "")
                .replacingOccurrences(of: " ", with: "-")
            attachScreenshot("failure-\(testName)")
        }
        XCUIDevice.shared.orientation = .portrait
        try super.tearDownWithError()
    }

    // MARK: Launch

    @discardableResult
    func launch(_ arguments: [String]) -> XCUIApplication {
        let application = XCUIApplication()
        application.launchArguments = arguments
        application.launch()
        app = application
        XCTAssertTrue(element(AX.Library.screen).waitForExistence(timeout: Timeout.launch),
                      "The library screen did not appear after launch")
        return application
    }

    /// Terminates the app and launches it again WITHOUT `-uiTesting` (nothing is wiped).
    @discardableResult
    func relaunchKeepingState() -> XCUIApplication {
        app.terminate()
        XCTAssertTrue(app.wait(for: .notRunning, timeout: 10), "The app did not terminate")
        return launch(Launch.relaunch)
    }

    // MARK: Queries and waits

    func element(_ identifier: String) -> XCUIElement {
        app.descendants(matching: .any).matching(identifier: identifier).firstMatch
    }

    func elements(withIdentifierPrefix prefix: String) -> XCUIElementQuery {
        app.descendants(matching: .any).matching(NSPredicate(format: "identifier BEGINSWITH %@", prefix))
    }

    @discardableResult
    func waitFor(_ identifier: String, timeout: TimeInterval = Timeout.screen,
                 file: StaticString = #filePath, line: UInt = #line) -> XCUIElement {
        let target = element(identifier)
        XCTAssertTrue(target.waitForExistence(timeout: timeout),
                      "Timed out after \(Int(timeout)) s waiting for '\(identifier)'", file: file, line: line)
        return target
    }

    /// Polls `condition` (roughly once per second, plus once immediately) until it holds.
    @discardableResult
    func waitUntil(_ description: String, timeout: TimeInterval, _ condition: @escaping () -> Bool) -> Bool {
        if condition() { return true }
        let predicate = NSPredicate { _, _ in condition() }
        let expectation = XCTNSPredicateExpectation(predicate: predicate, object: nil)
        expectation.expectationDescription = description
        return XCTWaiter().wait(for: [expectation], timeout: timeout) == .completed
    }

    func waitForDisappearance(of target: XCUIElement, timeout: TimeInterval = Timeout.control) -> Bool {
        let expectation = XCTNSPredicateExpectation(predicate: NSPredicate(format: "exists == false"), object: target)
        return XCTWaiter().wait(for: [expectation], timeout: timeout) == .completed
    }

    /// Waits until the element's label satisfies `matches`; returns the last label seen.
    @discardableResult
    func waitForLabel(of target: XCUIElement, timeout: TimeInterval, description: String,
                      file: StaticString = #filePath, line: UInt = #line,
                      _ matches: @escaping (String) -> Bool) -> String {
        var last = ""
        let satisfied = waitUntil(description, timeout: timeout) {
            guard target.exists else { return false }
            last = target.label
            return matches(last)
        }
        XCTAssertTrue(satisfied, "\(description) (last label: '\(last)')", file: file, line: line)
        return last
    }

    func isVisible(_ target: XCUIElement) -> Bool {
        target.exists && target.isHittable
    }

    // MARK: Screenshots

    func attachScreenshot(_ name: String) {
        let attachment = XCTAttachment(screenshot: XCUIScreen.main.screenshot())
        attachment.name = name
        attachment.lifetime = .keepAlways
        add(attachment)
    }

    // MARK: Library and player navigation

    func openLibraryItem(_ title: String, file: StaticString = #filePath, line: UInt = #line) {
        let cell = waitFor(AX.Library.item(title), timeout: Timeout.screen, file: file, line: line)
        cell.tap()
        waitFor(AX.Player.screen, timeout: Timeout.screen, file: file, line: line)
        XCTAssertFalse(element(AX.Player.errorMessage).exists, "The player shows an error: \(element(AX.Player.errorMessage).label)",
                       file: file, line: line)
    }

    /// Returns a player control, revealing the auto-hiding chrome with a tap on the video when needed.
    func playerControl(_ identifier: String, timeout: TimeInterval = Timeout.control) -> XCUIElement {
        let control = element(identifier)
        if isVisible(control) { return control }
        for _ in 0..<2 {
            revealPlayerChrome()
            if waitUntil("'\(identifier)' becomes hittable", timeout: timeout / 2, { self.isVisible(control) }) {
                return control
            }
        }
        return control
    }

    /// Single tap on the upper part of the video surface (away from the centre play button and the
    /// bottom scrubber) to show the controls.
    func revealPlayerChrome() {
        let surface = element(AX.Player.surface)
        let target = surface.exists ? surface : element(AX.Player.screen)
        guard target.exists else { return }
        target.coordinate(withNormalizedOffset: CGVector(dx: 0.5, dy: 0.3)).tap()
    }

    /// Taps a player action that may live directly in the chrome or inside the "more" menu.
    func tapPlayerAction(_ identifier: String, file: StaticString = #filePath, line: UInt = #line) {
        let direct = playerControl(identifier, timeout: 4)
        if isVisible(direct) {
            direct.tap()
            return
        }
        let more = playerControl(AX.Player.moreButton)
        XCTAssertTrue(isVisible(more), "Neither '\(identifier)' nor the more button is reachable", file: file, line: line)
        more.tap()
        let item = element(identifier)
        XCTAssertTrue(item.waitForExistence(timeout: Timeout.control), "'\(identifier)' is not in the more menu", file: file, line: line)
        item.tap()
    }

    /// Current playback time in seconds from the AX.Player.currentTime label (chrome revealed).
    func currentPlaybackTime() -> TimeInterval? {
        let label = playerControl(AX.Player.currentTime, timeout: 4)
        guard label.exists else { return nil }
        return Self.seconds(fromClock: label.label)
    }

    func pausePlayback() {
        let button = playerControl(AX.Player.playPause)
        guard isVisible(button) else { return }
        if Self.labelMeansPlaying(button.label) { button.tap() }
        _ = waitUntil("playback paused", timeout: 4) { !button.exists || !Self.labelMeansPlaying(button.label) }
    }

    func resumePlayback() {
        let button = playerControl(AX.Player.playPause)
        guard isVisible(button) else { return }
        if !Self.labelMeansPlaying(button.label) { button.tap() }
    }

    /// A play/pause button labelled "Pause" means playback is running.
    static func labelMeansPlaying(_ label: String) -> Bool {
        label.range(of: "pause", options: .caseInsensitive) != nil
    }

    /// Opens the subtitle/track sheet from the player.
    func openTrackSheet(file: StaticString = #filePath, line: UInt = #line) {
        tapPlayerAction(AX.Player.subtitlesButton, file: file, line: line)
        waitFor(AX.Tracks.sheet, timeout: Timeout.screen, file: file, line: line)
    }

    /// Selects a subtitle row by exact track id (or the first row with the given id prefix).
    func selectSubtitleTrack(id: String? = nil, prefix: String? = nil, file: StaticString = #filePath, line: UInt = #line) {
        if !element(AX.Tracks.sheet).exists { openTrackSheet(file: file, line: line) }
        let row: XCUIElement
        if let id {
            row = element(AX.Tracks.subtitle(id))
        } else {
            row = elements(withIdentifierPrefix: AX.Tracks.subtitle(prefix ?? "")).firstMatch
        }
        XCTAssertTrue(row.waitForExistence(timeout: Timeout.playback),
                      "Subtitle row \(id ?? (prefix ?? "?") + "…") not found", file: file, line: line)
        if !row.isHittable { app.swipeUp() }
        row.tap()
        closeSheetIfPresent(AX.Tracks.sheet)
    }

    /// Dismisses a sheet (PixelSheet close button labelled "Close", else a downward swipe).
    func closeSheetIfPresent(_ sheetIdentifier: String) {
        let sheet = element(sheetIdentifier)
        guard sheet.exists else { return }
        let closeButtons = app.buttons.matching(NSPredicate(format: "label == 'Close' AND identifier != %@", AX.Player.close))
        for index in 0..<closeButtons.count {
            let button = closeButtons.element(boundBy: index)
            if button.exists && button.isHittable {
                button.tap()
                break
            }
        }
        if !waitForDisappearance(of: sheet, timeout: 3), sheet.exists {
            sheet.swipeDown(velocity: .fast)
            _ = waitForDisappearance(of: sheet, timeout: 5)
        }
    }

    /// Waits until the subtitle overlay shows text satisfying `matches`; returns it.
    @discardableResult
    func waitForSubtitleText(timeout: TimeInterval = Timeout.playback, description: String,
                             file: StaticString = #filePath, line: UInt = #line,
                             _ matches: @escaping (String) -> Bool) -> String {
        let overlay = element(AX.Player.subtitleText)
        return waitForLabel(of: overlay, timeout: timeout, description: description, file: file, line: line) { label in
            !label.isEmpty && matches(label)
        }
    }

    func containsEnglishDialogue(_ text: String) -> Bool {
        let flattened = text.replacingOccurrences(of: "\n", with: " ")
        return Fixture.englishLines.contains { flattened.contains($0) }
    }

    func containsArabic(_ text: String) -> Bool {
        text.unicodeScalars.contains { (0x0600...0x06FF).contains($0.value) || (0xFB50...0xFEFF).contains($0.value) }
    }

    // MARK: Timing

    /// Opens the manual timing panel.
    @discardableResult
    func openTimingPanel(file: StaticString = #filePath, line: UInt = #line) -> XCUIElement {
        tapPlayerAction(AX.Player.timingButton, file: file, line: line)
        waitFor(AX.Timing.panel, timeout: Timeout.screen, file: file, line: line)
        return waitFor(AX.Timing.offsetValue, timeout: Timeout.control, file: file, line: line)
    }

    func closeTimingPanel() {
        let panel = element(AX.Timing.panel)
        guard panel.exists else { return }
        closeSheetIfPresent(AX.Timing.panel)
        if panel.exists {
            // Compact panel toggled by its own button.
            let toggle = element(AX.Player.timingButton)
            if isVisible(toggle) { toggle.tap() }
            _ = waitForDisappearance(of: panel, timeout: 4)
        }
    }

    /// Waits for the offset readout to show `expected` (e.g. "+0.100", "0.000", "−2.500").
    @discardableResult
    func waitForOffset(_ expected: String, in readout: XCUIElement, timeout: TimeInterval = Timeout.control,
                       file: StaticString = #filePath, line: UInt = #line) -> String {
        waitForLabel(of: readout, timeout: timeout, description: "offset readout shows \(expected) s",
                     file: file, line: line) { label in
            Self.offsetToken(in: label) == expected
        }
    }

    // MARK: Parsing helpers (pure; unit-testable)

    /// "1:02:03" / "2:03" / "02:03.450" / "−0:05" -> seconds.
    static func seconds(fromClock text: String) -> TimeInterval? {
        let normalized = text.replacingOccurrences(of: "\u{2212}", with: "-")
        guard let range = normalized.range(of: #"-?\d+(:\d{1,2})+(\.\d+)?"#, options: .regularExpression) else {
            return nil
        }
        let token = String(normalized[range])
        let negative = token.hasPrefix("-")
        let parts = token.trimmingCharacters(in: CharacterSet(charactersIn: "-")).split(separator: ":")
        var total: TimeInterval = 0
        for part in parts {
            guard let value = Double(part) else { return nil }
            total = total * 60 + value
        }
        return negative ? -total : total
    }

    /// The signed offset token in a label: "+0.100 s" -> "+0.100", "0.000 s" -> "0.000",
    /// "−2.500 s" -> "−2.500" (U+2212, also accepts ASCII "-" and returns it as U+2212).
    static func offsetToken(in label: String) -> String? {
        guard let range = label.range(of: #"[+\-\x{2212}]?\d+\.\d{3}(?=\s*s\b)"#, options: .regularExpression) else {
            return nil
        }
        var token = String(label[range])
        if token.hasPrefix("-") { token = "\u{2212}" + token.dropFirst() }
        return token
    }

    static func offsetSeconds(in label: String) -> TimeInterval? {
        guard let token = offsetToken(in: label) else { return nil }
        return Double(token.replacingOccurrences(of: "\u{2212}", with: "-"))
    }

    /// Formats like `TimecodeFormatter.signedOffset`, without the unit: "+1.300", "−0.100", "0.000".
    static func formatOffset(_ seconds: TimeInterval) -> String {
        let millis = Int((seconds * 1000).rounded())
        if millis == 0 { return "0.000" }
        let sign = millis > 0 ? "+" : "\u{2212}"
        let magnitude = abs(millis)
        return "\(sign)\(magnitude / 1000).\(String(format: "%03d", magnitude % 1000))"
    }

    /// Fraction 0...1 from a progress label ("44%", "4 / 9", "4 of 9 lines") or an accessibility
    /// value ("44 percent").
    static func progressFraction(from text: String) -> Double? {
        if let range = text.range(of: #"\d+(\.\d+)?\s*(%|percent)"#, options: .regularExpression) {
            let digits = text[range].prefix { $0.isNumber || $0 == "." }
            if let value = Double(digits) { return min(1, value / 100) }
        }
        if let range = text.range(of: #"\d+\s*(/|of)\s*\d+"#, options: .regularExpression) {
            let numbers = text[range].split { !$0.isNumber }.compactMap { Double($0) }
            if numbers.count == 2, numbers[1] > 0 { return min(1, numbers[0] / numbers[1]) }
        }
        return nil
    }
}
